"""Regenerate lib/content/city-hubs/all.ts from data/*.json (run after adding a city)."""
import glob, os, json, re
D = os.path.join(os.path.dirname(__file__), '..', '..', 'lib', 'content', 'city-hubs')
files = sorted(glob.glob(D + '/data/*.json'))
rows = []
for f in files:
    c = json.load(open(f, encoding='utf-8')); slug = c['slug']
    rows.append((c['wave'], slug, 'c_' + re.sub(r'[^a-z0-9]', '_', slug)))
rows.sort()
out = ['// AUTO-GENERATED by scripts/city-hubs/gen-index.py — do not edit by hand.', "import type { CityHub } from './types';"]
out += [f"import {v} from './data/{s}.json';" for _, s, v in rows]
out.append('export const ALL_CITY_HUBS = [' + ', '.join(v for _, _, v in rows) + '] as CityHub[];')
open(D + '/all.ts', 'w').write('\n'.join(out) + '\n')
print(len(rows), 'cities')
